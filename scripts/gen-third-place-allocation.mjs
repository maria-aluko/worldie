// Generates src/lib/data/third-place-allocation.ts from FIFA's Annex C table.
//
// Source of truth: Wikipedia mirror of FIFA "Regulations for the FIFA World Cup 26"
// Annex C — all C(12,8)=495 scenarios for assigning the eight best third-placed
// teams to the eight "group winner vs 3rd" Round-of-32 ties.
//
// Run: node scripts/gen-third-place-allocation.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const SRC =
  "https://en.wikipedia.org/wiki/Template:2026_FIFA_World_Cup_third-place_table?action=raw";

// The eight Round-of-32 ties that host a third-placed team, in the column order
// used by the source table, each with the group winner's group and the set of
// groups whose third-placed team may be drawn into that tie.
const SLOTS = [
  { slot: "1A", candidates: "CEFHI" }, // Match 79
  { slot: "1B", candidates: "EFGIJ" }, // Match 85
  { slot: "1D", candidates: "BEFIJ" }, // Match 81
  { slot: "1E", candidates: "ABCDF" }, // Match 74
  { slot: "1G", candidates: "AEHIJ" }, // Match 82
  { slot: "1I", candidates: "CDFGH" }, // Match 77
  { slot: "1K", candidates: "DEIJL" }, // Match 87
  { slot: "1L", candidates: "EHIJK" }, // Match 80
];
const GROUPS = "ABCDEFGHIJKL";

const clean = (c) => c.replace(/'''/g, "").replace(/<[^>]*>/g, "").trim();

function parse(wikitext) {
  const lines = wikitext.split("\n");
  const rows = {};
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(/^!\s*scope="row"\s*\|\s*(\d+)\s*$/);
    if (!m) continue;
    const no = Number(m[1]);
    // Collect every cell ("| ...") line until the next row separator.
    const cells = [];
    for (let j = i + 1; j < lines.length; j++) {
      const line = lines[j];
      if (line.startsWith("|-") || line.startsWith("|}")) break;
      if (line.startsWith('! scope="row"')) break;
      if (line.startsWith("|")) {
        cells.push(...line.slice(1).split("||").map(clean));
      }
    }
    if (cells.length !== 20) {
      throw new Error(`Row ${no}: expected 20 cells, got ${cells.length}`);
    }
    const qualifierCells = cells.slice(0, 12);
    const matchupCells = cells.slice(12);

    const qualifiers = [];
    qualifierCells.forEach((c, idx) => {
      if (c === "") return;
      const expected = GROUPS[idx];
      if (c !== expected) {
        throw new Error(`Row ${no}: group cell ${idx} is "${c}", expected "${expected}"`);
      }
      qualifiers.push(expected);
    });
    if (qualifiers.length !== 8) {
      throw new Error(`Row ${no}: ${qualifiers.length} qualifiers, expected 8`);
    }

    const mapping = {};
    matchupCells.forEach((c, idx) => {
      const g = c.replace(/^3/, "");
      const { slot, candidates } = SLOTS[idx];
      if (!candidates.includes(g)) {
        throw new Error(`Row ${no}: ${slot} drew 3${g}, not in candidate set ${candidates}`);
      }
      if (!qualifiers.includes(g)) {
        throw new Error(`Row ${no}: ${slot} drew 3${g}, but ${g} did not qualify`);
      }
      mapping[slot] = g;
    });

    const assigned = [...new Set(Object.values(mapping))].sort().join("");
    const key = [...qualifiers].sort().join("");
    if (assigned !== key) {
      throw new Error(`Row ${no}: assigned thirds ${assigned} != qualifiers ${key}`);
    }
    if (rows[key]) throw new Error(`Duplicate key ${key} (row ${no})`);
    rows[key] = mapping;
  }
  const count = Object.keys(rows).length;
  if (count !== 495) throw new Error(`Parsed ${count} rows, expected 495`);
  return rows;
}

function emit(rows) {
  const slots = SLOTS.map((s) => `"${s.slot}"`).join(" | ");
  const entries = Object.keys(rows)
    .sort()
    .map((key) => {
      const m = rows[key];
      const body = SLOTS.map((s) => `"${s.slot}": "${m[s.slot]}"`).join(", ");
      return `  ${key}: { ${body} },`;
    })
    .join("\n");
  return `// AUTO-GENERATED by scripts/gen-third-place-allocation.mjs — do not edit by hand.
//
// FIFA World Cup 2026 Annex C: assignment of the eight best third-placed teams to
// the eight "group winner vs 3rd" Round-of-32 ties, for each of the 495 possible
// combinations of which groups produce a qualifying third-placed team.
//
// Key: the eight qualifying third-place groups, sorted, joined (e.g. "ABCEGIKL").
// Value: winner slot -> the group letter whose third-placed team plays there.

/** The eight group-winner slots that host a third-placed team in the Round of 32. */
export type WinnerSlot = ${slots};

export type ThirdPlaceMapping = Record<WinnerSlot, string>;

export const THIRD_PLACE_ALLOCATION: Record<string, ThirdPlaceMapping> = {
${entries}
};
`;
}

const res = await fetch(SRC, { headers: { "User-Agent": "2026-wc-builder/1.0" } });
if (!res.ok) throw new Error(`Fetch failed: ${res.status}`);
const wikitext = await res.text();
const rows = parse(wikitext);
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "data", "third-place-allocation.ts");
writeFileSync(out, emit(rows));
console.log(`Wrote ${Object.keys(rows).length} combinations to ${out}`);
